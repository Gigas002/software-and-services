#!/usr/bin/env bash
# Bump steam-frozen to Valve's current stable steamrt64 client: fetch the
# client manifest, rewrite the generated block in PKGBUILD (pkgver = manifest
# version, one source + sha256 per zip) and regenerate .SRCINFO.
#
#   ./update.sh            # current stable client
#   ./update.sh MANIFEST   # use a manifest file you already have
set -euo pipefail
cd "$(dirname "$0")"

cdn=https://client-update.steamstatic.com
# runtime_scout is the 32-bit Steam Runtime 1, never packaged
skip='^runtime_scout_'

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

if [[ $# -ge 1 ]]; then
    cp "$1" "$tmp/manifest"
else
    echo ":: Fetching $cdn/steam_client_steamrt64..."
    curl -fsSL "$cdn/steam_client_steamrt64" -o "$tmp/manifest"
fi

# VDF: "steamrt64" { "version" "N"  "<pkg>" { "file" "..." "sha2" "..." ... } ... }
awk -v skip="$skip" '
    { gsub(/\r/, "") }
    $1 == "\"version\"" && depth == 1 { gsub(/"/, "", $2); print "version", $2 }
    $1 == "{" { depth++; next }
    $1 == "}" { if (depth == 2 && name !~ skip) print "pkg", name, file, sha; depth--; file = sha = ""; next }
    depth == 1 && NF == 1 { name = $1; gsub(/"/, "", name) }
    depth == 2 && $1 == "\"file\"" { file = $2; gsub(/"/, "", file) }
    depth == 2 && $1 == "\"sha2\"" { sha = $2; gsub(/"/, "", sha) }
' "$tmp/manifest" > "$tmp/parsed"

new=$(awk '$1 == "version" { print $2 }' "$tmp/parsed")
[[ $new =~ ^[0-9]+$ ]] || { echo "error: no version in manifest" >&2; exit 1; }
count=$(grep -c '^pkg ' "$tmp/parsed")
if awk '$1 == "pkg" && (NF != 4 || $4 !~ /^[0-9a-f]{64}$/) { bad = 1 } END { exit !bad }' "$tmp/parsed"; then
    echo "error: manifest entry without file or sha2" >&2
    exit 1
fi
old=$(sed -n 's/^pkgver=//p' PKGBUILD)
echo "   client: $old -> $new ($count zips)"

{
    echo "# BEGIN client (generated by update.sh, do not edit)"
    echo "pkgver=$new"
    echo "_client=("
    awk '$1 == "pkg" { print "  " $3 }' "$tmp/parsed"
    echo ")"
    echo "_client_sha256sums=("
    awk '$1 == "pkg" { print "  " $4 }' "$tmp/parsed"
    echo ")"
    echo "_manifest_sha256=$(sha256sum "$tmp/manifest" | cut -d' ' -f1)"
    echo "# END client"
} > "$tmp/block"

awk -v block="$tmp/block" '
    /^# BEGIN client/ { while ((getline line < block) > 0) print line; skipping = 1; next }
    /^# END client/ { skipping = 0; next }
    !skipping
' PKGBUILD > "$tmp/PKGBUILD"
if [[ $new != "$old" ]]; then
    sed -i 's/^pkgrel=.*/pkgrel=1/' "$tmp/PKGBUILD"
fi
cat "$tmp/PKGBUILD" > PKGBUILD
# the client reads its version from the manifest: it's shipped in package/
cp "$tmp/manifest" steam_client_steamrt64.manifest

echo ":: Regenerating .SRCINFO..."
makepkg --printsrcinfo > .SRCINFO

echo ":: Done. Build with: makepkg -s"
